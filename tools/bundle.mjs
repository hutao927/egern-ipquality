/**
 * Bundler: splices src/core.js into each entry script.
 *
 * Egern loads a script from a single URL (remote or local path) and has
 * no module resolution, so every script must be self-contained. Rather
 * than maintaining three copies of the core by hand, the entry scripts
 * in src/ carry a marker block:
 *
 *     /* ==== CORE:BEGIN ==== *​/
 *     ...generated...
 *     /* ==== CORE:END ==== *​/
 *
 * and this tool regenerates everything between the markers from
 * src/core.js. Run it after editing the core:
 *
 *     node tools/bundle.mjs
 *
 * Outputs to scripts/ (the install-ready files).
 */

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const srcDir = join(root, 'src');
const outDir = join(root, 'scripts');

const BEGIN = '/* ==== CORE:BEGIN ==== */';
const END = '/* ==== CORE:END ==== */';

/**
 * Convert an ES module's exports into plain declarations that can be
 * inlined into another module.
 *
 * The core only uses named `export function` / `export const`, so
 * stripping the `export ` keyword is sufficient and keeps the emitted
 * code readable (important: users may need to inspect it locally).
 */
function inlineCore(source) {
  // Drop the module doc-comment's `export` keywords, and any
  // `export { ... }` statement.
  let out = source.replace(/^export\s+(?=(async\s+)?(function|const|let|var|class)\b)/gm, '');
  out = out.replace(/^export\s*\{[^}]*\};?\s*$/gm, '');
  return out.trim();
}

/** Collision guard: the inlined core must not clash with entry code. */
function findTopLevelNames(source) {
  const names = new Set();
  const re = /^(?:async\s+)?function\s+([A-Za-z_$][\w$]*)|^(?:const|let|var)\s+([A-Za-z_$][\w$]*)/gm;
  let m;
  while ((m = re.exec(source)) !== null) {
    names.add(m[1] || m[2]);
  }
  return names;
}

function buildEntry(entryFile, coreCode) {
  const entryPath = join(srcDir, entryFile);
  const entry = readFileSync(entryPath, 'utf8');

  const beginIdx = entry.indexOf(BEGIN);
  const endIdx = entry.indexOf(END);
  if (beginIdx === -1 || endIdx === -1 || endIdx < beginIdx) {
    throw new Error(`${entryFile}: missing ${BEGIN} / ${END} markers`);
  }

  // Names defined outside the marker block must not collide with the core.
  const outside = entry.slice(0, beginIdx) + entry.slice(endIdx + END.length);
  const coreNames = findTopLevelNames(coreCode);
  const outsideNames = findTopLevelNames(outside);
  const collisions = [...coreNames].filter((n) => outsideNames.has(n));
  if (collisions.length > 0) {
    throw new Error(`${entryFile}: name collision with core: ${collisions.join(', ')}`);
  }

  const bundled =
    entry.slice(0, beginIdx) +
    BEGIN +
    '\n// ---- begin inlined core (generated by tools/bundle.mjs) ----\n' +
    coreCode +
    '\n// ---- end inlined core ----\n' +
    END +
    entry.slice(endIdx + END.length);

  return bundled;
}

function main() {
  const corePath = join(srcDir, 'core.js');
  const coreRaw = readFileSync(corePath, 'utf8');
  const coreCode = inlineCore(coreRaw);

  if (/\bexport\b/.test(coreCode)) {
    throw new Error('core.js still contains `export` after inlining; check the transform');
  }

  mkdirSync(outDir, { recursive: true });

  const entries = readdirSync(srcDir).filter((f) => f.endsWith('.js') && f !== 'core.js');
  if (entries.length === 0) throw new Error('no entry scripts found in src/');

  for (const entry of entries) {
    const bundled = buildEntry(entry, coreCode);
    const outPath = join(outDir, entry);
    writeFileSync(outPath, bundled, 'utf8');
    const lines = bundled.split('\n').length;
    console.log(`  bundled  ${entry}  ->  scripts/${entry}  (${lines} lines)`);
  }
  console.log(`\n${entries.length} script(s) written to scripts/\n`);
}

main();
