/**
 * Discover the current egress IP as the outside world sees it.
 * Race all endpoints and take the first valid answer; this both
 * improves accuracy (agrees on multiple sources) and speed.
 */
async function detectEgressIP(ctx, options = {}) {
  const { policy, prefer = 'auto', timeout = 8000 } = options;
  const pools = [];
  if (prefer === '4' || prefer === 'auto' || prefer === 'both') pools.push(...IP_ECHO_ENDPOINTS.v4);
  if (prefer === '6' || prefer === 'auto' || prefer === 'both') pools.push(...IP_ECHO_ENDPOINTS.v6);

  const settled = await Promise.allSettled(
    pools.map(async (endpoint) => {
      const text = await getText(ctx, endpoint.url, { policy, timeout });
      if (!text) return null;
      const candidate = text.split(/\s+/)[0];
      if (!isIPv4(candidate) && !isIPv6(candidate)) return null;
      if (isPrivateIP(candidate)) return null;
      return { ip: candidate, family: endpoint.family, source: endpoint.url };
    }),
  );

  for (const result of settled) {
    if (result.status === 'fulfilled' && result.value) return result.value;
  }
  return null;
}

