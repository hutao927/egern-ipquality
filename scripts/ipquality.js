function computeRiskScore(signals) {
  const entries = [];
  const push = (name, score, note) => {
    if (score === null || !Number.isFinite(score)) return;
    entries.push({ name, score: clamp(Math.round(score), 0, 100), note: note || '' });
  };

  const { ipApiIs, ipApiCom, ipInfo, abuse, scamalytics, ipqs, ipregistry } = signals;

  if (abuse && abuse.score !== null) {
    push('AbuseIPDB', abuse.score, `${abuse.reports ?? 0} reports/90d`);
  }

  if (ipApiIs) {
    let s = 0;
    if (ipApiIs.isProxy) s += 30;
    if (ipApiIs.isVPN) s += 25;
    if (ipApiIs.isTor) s += 45;
    if (ipApiIs.isAbuser) s += 40;
    if (ipApiIs.isCrawler) s += 15;
    if (ipApiIs.isDatacenter) s += 20;
    if (ipApiIs.abuseScore !== null) s = Math.max(s, ipApiIs.abuseScore);
    const flags = [
      ipApiIs.isProxy && 'proxy', ipApiIs.isVPN && 'VPN', ipApiIs.isTor && 'Tor',
      ipApiIs.isAbuser && 'abuser', ipApiIs.isCrawler && 'crawler',
      ipApiIs.isDatacenter && 'datacenter',
    ].filter(Boolean);
    push('ipapi.is', s, flags.join('/') || 'clean');
  }

  if (scamalytics && scamalytics.score !== null) push('Scamalytics', scamalytics.score, scamalytics.risk);
  if (ipqs && ipqs.score !== null) push('IPQS', ipqs.score, ipqs.risk);

  if (ipregistry) {
    let s = 0;
    if (ipregistry.isProxy) s += 25;
    if (ipregistry.isVPN) s += 25;
    if (ipregistry.isTor) s += 45;
    if (ipregistry.isAbuser) s += 30;
    if (ipregistry.isAttacker) s += 35;
    if (ipregistry.isCloudProvider) s += 15;
    push('ipregistry', s, s > 0 ? 'flags raised' : 'clean');
  }

  if (ipApiCom) {
    let s = 0;
    if (ipApiCom.isProxy) s += 30;
    if (ipApiCom.isHosting) s += 20;
    push('ip-api.com', s, [
      ipApiCom.isProxy && 'proxy', ipApiCom.isHosting && 'hosting',
      ipApiCom.isMobile && 'mobile',
    ].filter(Boolean).join('/') || 'clean');
  }

  if (ipInfo) {
    let s = 0;
    if (ipInfo.isProxy) s += 30;
    if (ipInfo.isVPN) s += 25;
    if (ipInfo.isTor) s += 45;
    if (ipInfo.isRelay) s += 20;
    if (ipInfo.isHosting) s += 20;
    push('ipinfo', s, s > 0 ? 'privacy flags' : 'clean');
  }

  if (entries.length === 0) return { total: null, level: 'unknown', entries };

  // Bias toward the worst single signal: one confident "Tor exit"
  // should not be averaged away by quiet databases.
  const mean = entries.reduce((sum, e) => sum + e.score, 0) / entries.length;
  const worst = Math.max(...entries.map((e) => e.score));
  const total = Math.round(mean * 0.45 + worst * 0.55);
  return { total, level: riskLevel(total), entries };
}

function riskLevel(score) {
  if (score === null || score === undefined) return 'unknown';
  if (score < 20) return 'VeryLow';
  if (score < 40) return 'Low';
  if (score < 60) return 'Medium';
  if (score < 80) return 'High';
  return 'VeryHigh';
}

