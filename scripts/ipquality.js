/**
 * Compare the current IP against history and report what changed.
 * Returns null when there is no previous record.
 */
function trackIPChange(ctx, model, maxHistory = 20) {
  const now = new Date().toISOString();
  let history = [];
  try {
    history = ctx.storage.getJSON(KEYS.ipHistory) || [];
  } catch {
    history = [];
  }
  if (!Array.isArray(history)) history = [];

  const primary = model.signals.ipApiCom || model.signals.ipApiIs || model.signals.ipInfo || {};
  const entry = {
    ip: model.ip,
    at: now,
    country: str(primary.country),
    asn: primary.asn ?? null,
    org: str(primary.isp) || str(primary.org),
    score: model.score.total,
    level: model.score.level,
  };

  const previous = history.length > 0 ? history[history.length - 1] : null;
  const changed = !previous || previous.ip !== entry.ip;

  if (changed) {
    history.push(entry);
    if (history.length > maxHistory) history = history.slice(-maxHistory);
    try {
      ctx.storage.setJSON(KEYS.ipHistory, history);
    } catch {
      // best effort
    }
  }

  if (!previous) return { changed: true, first: true, previous: null, current: entry };
  return {
    changed: previous.ip !== entry.ip,
    first: false,
    previous,
    current: entry,
    ipChanged: previous.ip !== entry.ip,
    countryChanged: previous.country !== entry.country,
    asnChanged: previous.asn !== entry.asn,
    scoreDelta:
      previous.score !== null && entry.score !== null ? entry.score - previous.score : null,
  };
}

/** Read stored IP history, newest first. */
function getIPHistory(ctx) {
  try {
    const history = ctx.storage.getJSON(KEYS.ipHistory);
    return Array.isArray(history) ? [...history].reverse() : [];
  } catch {
    return [];
  }
}

