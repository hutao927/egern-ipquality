function isWidget(ctx) {
  return typeof ctx.widgetFamily === 'string' && ctx.widgetFamily.length > 0;
}

function env(ctx, key, fallback = '') {
  const raw = ctx.env && ctx.env[key];
  if (raw === undefined || raw === null) return fallback;
  const value = String(raw).trim();
  return value === '' ? fallback : value;
}

function envFlag(ctx, key, fallback = false) {
  const raw = env(ctx, key, '');
  if (raw === '') return fallback;
  return /^(1|true|yes|on|y)$/i.test(raw);
}

function envInt(ctx, key, fallback, min, max) {
  const raw = env(ctx, key, '');
  if (raw === '') return fallback;
  const parsed = Number.parseInt(raw, 10);
  if (!Number.isFinite(parsed)) return fallback;
  if (min !== undefined && parsed < min) return min;
  if (max !== undefined && parsed > max) return max;
  return parsed;
}

/** Await a promise with a hard deadline; never rejects. */
function withTimeout(promise, ms, fallback = null) {
  let timer;
  const guard = new Promise((resolve) => {
    timer = setTimeout(() => resolve(fallback), ms);
  });
  return Promise.race([
    Promise.resolve(promise).catch(() => fallback),
    guard,
  ]).finally(() => clearTimeout(timer));
}

function safeJSON(text) {
  if (typeof text !== 'string') return null;
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

function str(value, fallback = '') {
  if (value === null || value === undefined) return fallback;
  const s = String(value).trim();
  return s === '' || s === 'null' || s === 'undefined' ? fallback : s;
}

function num(value) {
  if (value === null || value === undefined || value === '') return null;
  const n = Number(value);
  return Number.isFinite(n) ? n : null;
}

function clamp(value, lo, hi) {
  return Math.min(hi, Math.max(lo, value));
}

/** Read a named group out of a text body, tolerating whitespace. */
function pick(text, regex, group = 1) {
  if (typeof text !== 'string') return '';
  const m = regex.exec(text);
  return m && m[group] !== undefined ? String(m[group]).trim() : '';
}

