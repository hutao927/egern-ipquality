/**
 * Low-level GET that returns a normalised result instead of throwing,
 * so callers can distinguish "blocked" from "network failed".
 *
 * `redirect: 'manual'` is the default because several services encode
 * their geo-decision in the redirect target.
 */
async function httpGet(ctx, url, options = {}) {
  const started = Date.now();
  const result = {
    ok: false,
    status: 0,
    headers: null,
    body: '',
    location: '',
    error: '',
    ms: 0,
  };
  try {
    const init = {
      headers: {
        'User-Agent': options.userAgent || UA_BROWSER,
        Accept: options.accept || '*/*',
        'Accept-Language': options.language || 'en-US,en;q=0.9',
        ...(options.headers || {}),
      },
      timeout: options.timeout || DEFAULT_TIMEOUT,
    };
    if (options.policy) init.policy = options.policy;
    if (options.redirect) init.redirect = options.redirect;
    if (options.method && options.method !== 'GET') init.method = options.method;
    // `body` is only valid on non-GET requests; passing it on a GET
    // makes some runtimes throw.
    if (options.body !== undefined && options.method && options.method !== 'GET') {
      init.body = options.body;
    }

    const resp = await ctx.http.get(url, init);
    result.status = resp.status;
    result.headers = resp.headers;
    if (resp.headers && typeof resp.headers.get === 'function') {
      result.location = str(resp.headers.get('location'));
    }
    if (options.wantBody !== false) {
      result.body = await resp.text().catch(() => '');
    }
    result.ok = resp.status >= 200 && resp.status < 300;
  } catch (error) {
    result.error = str((error && error.message) || error).slice(0, 100);
  }
  result.ms = Date.now() - started;
  return result;
}

/** GET and parse JSON, returning null on any failure. */
async function getJSON(ctx, url, options = {}) {
  const res = await httpGet(ctx, url, {
    ...options,
    accept: 'application/json, text/plain, */*',
  });
  if (!res.ok) return null;
  return safeJSON(res.body);
}

/** GET and return trimmed text, or null on failure. */
async function getText(ctx, url, options = {}) {
  const res = await httpGet(ctx, url, {
    ...options,
    accept: 'text/plain, */*',
  });
  return res.ok ? res.body.trim() : null;
}

