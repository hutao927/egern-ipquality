async function fetchCloudflareTrace(ctx, options = {}) {
  const text = await withTimeout(
    getText(ctx, 'https://www.cloudflare.com/cdn-cgi/trace', options),
    8000,
  );
  if (!text) return null;
  const map = {};
  for (const line of text.split('\n')) {
    const idx = line.indexOf('=');
    if (idx > 0) map[line.slice(0, idx).trim()] = line.slice(idx + 1).trim();
  }
  return {
    source: 'cloudflare',
    country: str(map.loc),
    ip: str(map.ip),
    colo: str(map.colo),
    warp: str(map.warp),
    gateway: str(map.gateway),
  };
}

