/**
 * Suggest Egern rules based on what the current IP can and cannot do.
 *
 * The idea: if a service is blocked on the current egress but the user
 * has a working policy, route that service's domains through it.
 */
function generateRules(model, options = {}) {
  const { targetPolicy = 'PROXY', includeStreaming = true } = options;
  const rules = [];
  const notes = [];

  const blocked = model.services.filter((s) => s.status === 'no');
  const partial = model.services.filter((s) => s.status === 'partial');

  // Domains each service needs proxied when blocked.
  const SERVICE_DOMAINS = {
    chatgpt: ['openai.com', 'chatgpt.com', 'oaistatic.com', 'oaiusercontent.com'],
    netflix: ['netflix.com', 'nflxvideo.net', 'nflximg.net', 'nflxso.net'],
    youtube: ['youtube.com', 'googlevideo.com', 'ytimg.com', 'youtu.be'],
    disney: ['disneyplus.com', 'bamgrid.com', 'dssott.com'],
    primevideo: ['primevideo.com', 'aiv-cdn.net', 'amazonaws.com'],
    tiktok: ['tiktok.com', 'tiktokcdn.com', 'byteoversea.com'],
    reddit: ['reddit.com', 'redd.it', 'redditmedia.com'],
  };

  if (includeStreaming) {
    for (const service of [...blocked, ...partial]) {
      const domains = SERVICE_DOMAINS[service.id];
      if (!domains) continue;
      for (const domain of domains) {
        rules.push({ type: 'domain_suffix', match: domain, policy: targetPolicy });
      }
      notes.push(`${service.name} 当前${service.status === 'no' ? '被屏蔽' : '部分受限'}，已为其域名生成分流规则`);
    }
  }

  // Route the current region through DIRECT unless it is a datacenter,
  // in which case keeping it proxied is usually intended.
  const primary = model.signals.ipApiCom || model.signals.ipApiIs || model.signals.ipInfo || {};
  const usage = model.usageType || { key: 'other' };

  if (usage.key === 'hosting') {
    notes.push('当前为机房 IP：如需本地服务直连，建议为国内域名单独配置 DIRECT 规则');
  }
  if (primary.country && primary.country !== 'CN') {
    rules.push({ type: 'geoip', match: 'CN', policy: 'DIRECT', no_resolve: true });
    notes.push('已生成「中国大陆 IP 直连」规则，避免国内流量绕行代理');
  }

  // De-duplicate while preserving order.
  const seen = new Set();
  const unique = rules.filter((r) => {
    const key = `${r.type}:${r.match}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });

  return { rules: unique, notes, yaml: renderRulesYAML(unique) };
}

/** Render rules as profile-ready YAML. */
function renderRulesYAML(rules) {
  if (rules.length === 0) return 'rules: []';
  const lines = ['rules:'];
  for (const rule of rules) {
    lines.push(`  - ${rule.type}:`);
    lines.push(`      match: ${rule.match}`);
    lines.push(`      policy: ${rule.policy}`);
    if (rule.no_resolve) lines.push('      no_resolve: true');
  }
  return lines.join('\n');
}

