/** Run the selected probes in parallel with a shared deadline. */
async function probeServices(ctx, options = {}) {
  const { policy, ids, deadline = 15000, concurrency = 6 } = options;
  const selected = ids && ids.length > 0
    ? SERVICE_PROBES.filter((p) => ids.includes(p.id))
    : SERVICE_PROBES;

  const out = [];
  // Bounded concurrency keeps the radio from being hammered and avoids
  // tripping per-host rate limits.
  for (let i = 0; i < selected.length; i += concurrency) {
    const batch = selected.slice(i, i + concurrency);
    const batchResults = await Promise.all(
      batch.map(async (probe) => {
        const base = {
          id: probe.id,
          name: probe.name,
          group: probe.note,
          status: 'unknown',
          region: '',
          type: '',
          note: '',
          detail: '',
        };
        try {
          const result = await withTimeout(
            probe.run({ ctx, options: { policy, timeout: deadline } }),
            deadline,
            { status: 'unknown', note: '超时' },
          );
          return { ...base, ...(result || {}) };
        } catch (error) {
          return { ...base, note: str((error && error.message) || error).slice(0, 60) };
        }
      }),
    );
    out.push(...batchResults);
  }
  return out;
}

